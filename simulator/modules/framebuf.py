class FrameBuffer:
    MONO_HLSB = 0
    MONO_HMSB = 1
    MONO_VLSB = 2
    RGB565 = 3
    GS8 = 4

    def __init__(self, buffer, width, height, format=MONO_HLSB, stride=None):
        self.buffer = buffer
        self.width = width
        self.height = height
        self.format = format
        self.stride = stride if stride else width

    def pixel(self, x, y, color=None):
        if x < 0 or x >= self.width or y < 0 or y >= self.height:
            return
        if self.format == FrameBuffer.MONO_HLSB:
            index = (y // 8) * self.stride + x
            bit = y % 8
            if color is None:
                return (self.buffer[index] >> bit) & 1
            if color:
                self.buffer[index] |= (1 << bit)
            else:
                self.buffer[index] &= ~(1 << bit)
        return None

    def fill(self, color):
        if self.format == FrameBuffer.MONO_HLSB:
            val = 0xFF if color else 0x00
            for i in range(len(self.buffer)):
                self.buffer[i] = val

    def blit(self, fbuf, x, y):
        for fy in range(fbuf.height):
            for fx in range(fbuf.width):
                if x + fx < self.width and y + fy < self.height:
                    color = fbuf.pixel(fx, fy)
                    self.pixel(x + fx, y + fy, color)

    def line(self, x1, y1, x2, y2, color):
        dx = abs(x2 - x1)
        dy = abs(y2 - y1)
        sx = 1 if x1 < x2 else -1
        sy = 1 if y1 < y2 else -1
        err = dx - dy

        while x1 != x2 or y1 != y2:
            self.pixel(x1, y1, color)
            e2 = 2 * err
            if e2 > -dy:
                err -= dy
                x1 += sx
            if e2 < dx:
                err += dx
                y1 += sy

    def rect(self, x, y, w, h, color):
        self.line(x, y, x + w - 1, y, color)
        self.line(x, y + h - 1, x + w - 1, y + h - 1, color)
        self.line(x, y, x, y + h - 1, color)
        self.line(x + w - 1, y, x + w - 1, y + h - 1, color)

    def fill_rect(self, x, y, w, h, color):
        for dy in range(h):
            for dx in range(w):
                self.pixel(x + dx, y + dy, color)

