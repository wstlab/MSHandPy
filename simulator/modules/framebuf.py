    def scroll(self, dx, dy):
        new_buffer = bytearray(len(self.buffer))
        new_fb = FrameBuffer(new_buffer, self.width, self.height, self.format, self.stride)
        for y in range(self.height):
            for x in range(self.width):
                src_x = x - dx
                src_y = y - dy
                if 0 <= src_x < self.width and 0 <= src_y < self.height:
                    color = self.pixel(src_x, src_y)
                    new_fb.pixel(x, y, color)
        self.buffer[:] = new_buffer